//! External components: the WIT world written from each `extern component`
//! declaration, and the Rust adapter that builds the component from it.
//!
//! The split keeps languages apart. [`world`] turns a declaration into a WIT
//! world, which is the whole contract between the program and the external
//! code, and knows nothing of Rust. A language adapter then generates that
//! language's bindings from the world and builds the component. Rust is the
//! first adapter ([`rust`]): its bindings are `wit-bindgen`'s, wrapped in a
//! crate named `interface` that offers the trait the declaration describes.
//! Another language, such as Python through `componentize-py`, needs only an
//! adapter of its own, since nothing the host or the program does depends
//! on the language the component was written in.
//!
//! The world exports one interface, named after the component, holding the
//! program's types that the messages carry and a resource with a
//! constructor and one method per message. The host makes one instance of
//! the component for each place the program starts it, and one resource in
//! that instance, so each running external component has state of its own.

pub(crate) mod rust;

use inset_check::{External, ExternalTypeKind, WitType, wit_field_name, wit_type_name};

/// WIT's keywords, which a name must escape with `%` to be used as one.
const KEYWORDS: [&str; 42] = [
    "as",
    "async",
    "bool",
    "borrow",
    "char",
    "constructor",
    "enum",
    "error-context",
    "export",
    "f32",
    "f64",
    "flags",
    "from",
    "func",
    "future",
    "import",
    "include",
    "interface",
    "list",
    "option",
    "own",
    "package",
    "record",
    "resource",
    "result",
    "s16",
    "s32",
    "s64",
    "s8",
    "static",
    "stream",
    "string",
    "tuple",
    "type",
    "u16",
    "u32",
    "u64",
    "u8",
    "use",
    "variant",
    "with",
    "world",
];

/// A name in WIT, escaped if it is a keyword.
fn escaped(name: String) -> String {
    if KEYWORDS.contains(&name.as_str()) {
        format!("%{name}")
    } else {
        name
    }
}

/// The WIT name of a type, variant or component. The checker has made sure
/// there is one.
pub(crate) fn type_name(name: &str) -> String {
    wit_type_name(name).unwrap_or_else(|| name.to_lowercase())
}

/// The WIT name of a field, parameter or message.
fn field_name(name: &str) -> String {
    wit_field_name(name).unwrap_or_else(|| name.to_lowercase())
}

/// The external component's WIT world, as `wit/world.wit`.
pub fn world(external: &External) -> String {
    let package = type_name(&external.name);
    let mut out = format!(
        "// Generated by `inset build` from the declaration of `{}`.\n\
         // It is written again on every build.\n\n\
         package inset:{package};\n\n",
        external.name
    );
    doc(&mut out, external.doc.as_deref(), "");
    out.push_str(&format!("interface {} {{\n", escaped(package.clone())));
    for ty in &external.types {
        doc(&mut out, ty.doc.as_deref(), "    ");
        let name = escaped(type_name(&ty.name));
        match &ty.kind {
            ExternalTypeKind::Record(fields) => {
                out.push_str(&format!("    record {name} {{\n"));
                for (field, field_doc, field_ty) in fields {
                    doc(&mut out, field_doc.as_deref(), "        ");
                    out.push_str(&format!(
                        "        {}: {},\n",
                        escaped(field_name(field)),
                        wit_type(field_ty)
                    ));
                }
            }
            ExternalTypeKind::Variant(cases) if cases.iter().all(|(_, _, t)| t.is_none()) => {
                out.push_str(&format!("    enum {name} {{\n"));
                for (case, case_doc, _) in cases {
                    doc(&mut out, case_doc.as_deref(), "        ");
                    out.push_str(&format!("        {},\n", escaped(type_name(case))));
                }
            }
            ExternalTypeKind::Variant(cases) => {
                out.push_str(&format!("    variant {name} {{\n"));
                for (case, case_doc, payload) in cases {
                    doc(&mut out, case_doc.as_deref(), "        ");
                    let case = escaped(type_name(case));
                    match payload {
                        Some(t) => out.push_str(&format!("        {case}({}),\n", wit_type(t))),
                        None => out.push_str(&format!("        {case},\n")),
                    }
                }
            }
        }
        out.push_str("    }\n\n");
    }
    out.push_str(&format!("    resource {} {{\n", escaped(package.clone())));
    out.push_str(
        "        /// Starts the component, before its first message and again after it restarts.\n",
    );
    out.push_str("        constructor();\n");
    for message in &external.messages {
        out.push('\n');
        doc(&mut out, message.doc.as_deref(), "        ");
        let params: Vec<String> = message
            .params
            .iter()
            .map(|p| format!("{}: {}", escaped(field_name(&p.name)), wit_type(&p.ty)))
            .collect();
        let ret = message
            .ret
            .as_ref()
            .map(|r| format!(" -> {}", wit_type(&r.ty)))
            .unwrap_or_default();
        out.push_str(&format!(
            "        {}: func({}){ret};\n",
            escaped(field_name(&message.name)),
            params.join(", ")
        ));
    }
    out.push_str("    }\n}\n\n");
    out.push_str(&format!(
        "world external {{\n    export {};\n}}\n",
        escaped(package)
    ));
    out
}

pub(crate) fn doc(out: &mut String, doc: Option<&str>, indent: &str) {
    for line in doc.into_iter().flat_map(str::lines) {
        out.push_str(indent);
        out.push_str("///");
        if !line.is_empty() && !line.starts_with(' ') {
            out.push(' ');
        }
        out.push_str(line);
        out.push('\n');
    }
}

fn wit_type(ty: &WitType) -> String {
    match ty {
        WitType::Bool => "bool".into(),
        WitType::Int { signed, bits } => format!("{}{bits}", if *signed { "s" } else { "u" }),
        WitType::F32 => "f32".into(),
        WitType::F64 => "f64".into(),
        WitType::Char => "char".into(),
        WitType::String => "string".into(),
        WitType::List(inner) => format!("list<{}>", wit_type(inner)),
        WitType::Option(inner) => format!("option<{}>", wit_type(inner)),
        WitType::Result(ok, err) => match (ok, err) {
            (None, None) => "result".into(),
            (Some(ok), None) => format!("result<{}>", wit_type(ok)),
            (None, Some(err)) => format!("result<_, {}>", wit_type(err)),
            (Some(ok), Some(err)) => format!("result<{}, {}>", wit_type(ok), wit_type(err)),
        },
        WitType::Tuple(elems) => format!(
            "tuple<{}>",
            elems.iter().map(wit_type).collect::<Vec<_>>().join(", ")
        ),
        WitType::Data(name) => escaped(type_name(name)),
    }
}
