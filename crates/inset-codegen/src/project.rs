//! The generated Cargo project, and building it with Cargo.

use std::fmt;
use std::path::{Path, PathBuf};
use std::process::Command;

use inset_check::{Program, Report};

use crate::generate;

/// The workspace's lock file and toolchain, which the generated project starts from.
const LOCK: &str = include_str!("../../../Cargo.lock");
const TOOLCHAIN: &str = include_str!("../../../rust-toolchain.toml");

/// A built program.
#[derive(Clone, Debug)]
pub struct Built {
    /// The WebAssembly component.
    pub component: PathBuf,
    /// What `rustc` said while building. Any warning is a compiler bug,
    /// as an error is.
    pub warnings: String,
}

#[derive(Debug)]
pub enum BuildError {
    /// The program has errors, or uses what cannot be compiled yet.
    Rejected(Vec<Report>),
    /// The project could not be written or built.
    Failed(String),
}

impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            BuildError::Rejected(reports) => write!(f, "the program has {} errors", reports.len()),
            BuildError::Failed(message) => f.write_str(message),
        }
    }
}

impl std::error::Error for BuildError {}

/// Writes the program's Rust as a Cargo project in `out_dir`, builds it
/// for `wasm32-wasip2`, and copies the component to
/// `out_dir/<package>.wasm`. Cargo builds in `target_dir`, or else where
/// it would by default.
pub fn build(
    program: &Program,
    out_dir: &Path,
    target_dir: Option<&Path>,
) -> Result<Built, BuildError> {
    let generated = generate(program).map_err(BuildError::Rejected)?;
    let runtime = Path::new(env!("CARGO_MANIFEST_DIR")).join("../inset-runtime");
    let runtime = runtime.canonicalize().unwrap_or(runtime);
    write(
        &out_dir.join("Cargo.toml"),
        &cargo_toml(&generated.package, &runtime),
    )?;
    write(&out_dir.join("rust-toolchain.toml"), TOOLCHAIN)?;
    write(&out_dir.join("Cargo.lock"), LOCK)?;
    write(&out_dir.join("src/lib.rs"), &generated.source)?;

    let cargo = |args: &[&str]| {
        let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
        let mut command = Command::new(cargo);
        command
            .args(args)
            .args(["--release", "--target", "wasm32-wasip2", "--quiet"])
            .current_dir(out_dir);
        if let Some(target_dir) = target_dir {
            command.arg("--target-dir").arg(target_dir);
        }
        command
            .output()
            .map_err(|e| BuildError::Failed(format!("cannot run cargo: {e}")))
    };
    // Each generated project is the root of a workspace of its own, so Cargo
    // gives two programs whose apps share a name the same fingerprint, and
    // in a target directory they share it would take one's build as the
    // other's. Cleaning the package first makes Cargo build it afresh.
    if target_dir.is_some() || std::env::var_os("CARGO_TARGET_DIR").is_some() {
        let cleaned = cargo(&["clean", "--package", &generated.package])?;
        if !cleaned.status.success() {
            return Err(BuildError::Failed(format!(
                "cargo could not clean {}:\n\n{}",
                generated.package,
                String::from_utf8_lossy(&cleaned.stderr)
            )));
        }
    }
    let output = cargo(&["build", "--message-format", "json-render-diagnostics"])?;
    let warnings = String::from_utf8_lossy(&output.stderr).into_owned();
    if !output.status.success() {
        return Err(BuildError::Failed(format!(
            "cargo could not build the generated Rust in {}. If the errors below are \
             in src/lib.rs, that is a bug in the Inset compiler.\n\n{warnings}",
            out_dir.display()
        )));
    }
    let built = artifact(&String::from_utf8_lossy(&output.stdout), &generated.package)
        .ok_or_else(|| BuildError::Failed("cargo built no WebAssembly component".into()))?;
    let component = out_dir.join(format!("{}.wasm", generated.package));
    std::fs::copy(&built, &component).map_err(|e| {
        BuildError::Failed(format!(
            "cannot copy {} to {}: {e}",
            built.display(),
            component.display()
        ))
    })?;
    Ok(Built {
        component,
        warnings,
    })
}

/// The generated project's manifest. `runtime` is the `inset-runtime`
/// crate it depends on.
pub fn cargo_toml(package: &str, runtime: &Path) -> String {
    let runtime = runtime
        .to_string_lossy()
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    format!(
        r#"# Generated by `inset build`. It is written again on every build.

[package]
name = "{package}"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
inset-runtime = {{ path = "{runtime}" }}

# Inset checks integer arithmetic in every build.
[profile.release]
overflow-checks = true

# A project of its own, wherever it is written.
[workspace]
"#
    )
}

/// Writes a file unless it already holds `contents`, so Cargo sees no
/// change when there is none.
fn write(path: &Path, contents: &str) -> Result<(), BuildError> {
    if std::fs::read_to_string(path).is_ok_and(|old| old == contents) {
        return Ok(());
    }
    let fail =
        |e: std::io::Error| BuildError::Failed(format!("cannot write {}: {e}", path.display()));
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(fail)?;
    }
    std::fs::write(path, contents).map_err(fail)
}

/// The `.wasm` file Cargo reports building for the package.
fn artifact(messages: &str, package: &str) -> Option<PathBuf> {
    let target = package.replace('-', "_");
    messages
        .lines()
        .filter_map(|line| serde_json::from_str::<serde_json::Value>(line).ok())
        .filter(|m| m["reason"] == "compiler-artifact" && m["target"]["name"] == target)
        .flat_map(|m| {
            m["filenames"]
                .as_array()
                .cloned()
                .unwrap_or_default()
                .into_iter()
        })
        .filter_map(|f| f.as_str().map(PathBuf::from))
        .find(|f| f.extension().is_some_and(|e| e == "wasm"))
}
