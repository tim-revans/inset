/// Exports an [`App`] as the program's entry points.
#[macro_export]
macro_rules! export {
    ($app:ty) => {
        const _: () = {
            struct Exported;

            impl $crate::bindings::exports::inset::host::app::Guest for Exported {
                fn describe() -> $crate::bindings::exports::inset::host::app::Manifest {
                    $crate::glue::describe::<$app>()
                }

                fn start(
                    restore: Option<Vec<u8>>,
                ) -> Result<(), $crate::bindings::exports::inset::host::app::Stopped> {
                    $crate::glue::start::<$app>(restore)
                }

                fn handle(
                    server: String,
                    request: $crate::bindings::exports::inset::host::app::Request,
                ) -> Result<
                    $crate::bindings::exports::inset::host::app::Response,
                    $crate::bindings::exports::inset::host::app::Stopped,
                > {
                    $crate::glue::handle(server, request)
                }
            }

    $crate::bindings::export_program!(Exported with_types_in $crate::bindings);
        };
    };
}
