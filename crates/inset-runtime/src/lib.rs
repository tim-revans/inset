//! The support library linked into every built Inset program.
//!
//! The compiler emits Rust that uses this crate, and builds it to one
//! WebAssembly component of the `program` world in `wit/inset.wit`. Nothing
//! here is visible to Inset source. `docs/language/runtime.md` records what
//! the runtime spike found and why the runtime is built this way.
//!
//! - **Components** are actors: each one is a task that owns its fields and
//!   handles one envelope from its mailbox at a time ([`Component`],
//!   [`Handle`]).
//! - **The executor** is a small single-threaded one written here, not Tokio.
//!   It runs until the whole program is idle before a request returns, which
//!   Tokio cannot do, and it polls tasks in a fixed order, so a requirement
//!   test runs the same way every time.
//! - **Capabilities** are owned, non-`Clone` handles to what the host grants
//!   ([`HttpServer`], [`Table`]).
//! - **Stored values** take the form the `inset-value` crate defines, which
//!   the test runner shares: [`Stored`] for a table's values and a
//!   component's saved state, and [`Key`] for a table's keys, whose bytes
//!   sort in key order. The compiler implements `Stored` for each data type
//!   a program declares, so serde's derives and attributes, which say how a
//!   JSON body looks, never change what is stored.
//! - **Failures** are not Rust panics where they can be avoided. A failed
//!   capability call or message ends its handler by dropping the handler's
//!   future, so the component's `failure` block can roll it back and the
//!   program carries on. A panic traps the WebAssembly instance, so the panic
//!   hook hands the host the state to start a fresh instance from.
//!
//! # Unsafe code
//!
//! The [`bindings`] module is generated by `wit-bindgen` from
//! `wit/inset.wit`, and the code it generates uses `unsafe` to move values
//! across the component boundary through the canonical ABI. That module is
//! the only place `unsafe` is allowed. The rest of the crate is safe Rust,
//! including the executor, whose wakers use [`std::task::Wake`].

