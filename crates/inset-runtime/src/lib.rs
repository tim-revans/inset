/// Bindings for `wit/inset.wit`, generated by `wit-bindgen`.
#[doc(hidden)]
#[allow(unsafe_code, clippy::all)]
pub mod bindings {
    wit_bindgen::generate!({
        path: "wit",
        world: "program",
        pub_export_macro: true,
        export_macro_name: "export_program",
        default_bindings_module: "inset_runtime::bindings",
    });
}

